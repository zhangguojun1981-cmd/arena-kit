#!/usr/bin/env node
/* Bundle the dock (src/dock.js + src/lib/*.js + src/embed/shell.js) into ONE
 * classic script for the Android build, where the dock is mounted inside the
 * arena.ai page (see src/embed/shell.js). No npm dependencies: the modules use
 * a small, consistent ES-module subset (named imports / exports only), so a
 * line-level transform into a CommonJS-style registry is enough.
 *
 * Outputs (committed; CI runs `--check` to make sure they are up to date):
 *   src/embed/assets.gen.js         CSS + dock.html body markup as strings
 *   src/embed/dock-embedded.gen.js  the bundle Rust include_str!()s (mobile)
 *   injected/totp.gen.js            src/lib/totp.js as a classic page script
 *                                   (window.__AK_TOTP__) for the login helper
 *
 * Usage: node scripts/bundle-dock.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const OUT_ASSETS = path.join(SRC, 'embed', 'assets.gen.js');
const OUT_BUNDLE = path.join(SRC, 'embed', 'dock-embedded.gen.js');
const OUT_TOTP = path.join(ROOT, 'injected', 'totp.gen.js');
const HEADER = '/* GENERATED by scripts/bundle-dock.mjs — do not edit. Run `node scripts/bundle-dock.mjs` after changing src/. */\n';

const read = (p) => fs.readFileSync(p, 'utf8');
const toId = (abs) => path.relative(SRC, abs).split(path.sep).join('/');

/* dock.html body without the module <script> tag (the bundle replaces it). */
export function extractMarkup(html) {
  const m = /<body[^>]*>([\s\S]*?)<\/body>/i.exec(html);
  if (!m) throw new Error('dock.html: <body> not found');
  return m[1].replace(/<script[\s\S]*?<\/script>\s*/gi, '').trim();
}

export function buildAssets({ css, html }) {
  return HEADER
    + '/* eslint-disable */\n'
    + 'export const CSS = ' + JSON.stringify(css) + ';\n'
    + 'export const MARKUP = ' + JSON.stringify(extractMarkup(html)) + ';\n';
}

/* Transform one ES module into a registry function body.
 * Supported: `import { a, b as c } from './x.js';`, `export function|async function|const|let|class`,
 * `export { a, b as c };`. Anything else starting with import/export is an error. */
export function transformModule(source, id) {
  const dir = path.posix.dirname(id);
  const exportsList = [];
  let out = source;

  out = out.replace(/(^|\n)import\s*\{([^}]*)\}\s*from\s*(['"])([^'"]+)\3\s*;?/g, (_m, lead, names, _q, spec) => {
    const target = path.posix.normalize(path.posix.join(dir, spec));
    const bindings = names.split(',').map((s) => s.trim()).filter(Boolean).map((s) => {
      const [name, alias] = s.split(/\s+as\s+/).map((x) => x.trim());
      return alias ? `${name}: ${alias}` : name;
    });
    return `${lead}const { ${bindings.join(', ')} } = __require(${JSON.stringify(target)});`;
  });
  out = out.replace(/(^|\n)export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)/g, (_m, lead, kind, name) => {
    exportsList.push([name, name]);
    return `${lead}${kind} ${name}`;
  });
  out = out.replace(/(^|\n)export\s*\{([^}]*)\}\s*;?/g, (_m, lead, names) => {
    for (const s of names.split(',').map((x) => x.trim()).filter(Boolean)) {
      const [name, alias] = s.split(/\s+as\s+/).map((x) => x.trim());
      exportsList.push([alias || name, name]);
    }
    return lead;
  });
  const leftover = /(^|\n)\s*(import|export)\b/.exec(out);
  if (leftover) throw new Error(`${id}: unsupported module syntax near: ${out.slice(leftover.index, leftover.index + 60).trim()}`);

  const tail = exportsList.map(([exp, local]) => `__exports.${exp} = ${local};`).join(' ');
  return `__define(${JSON.stringify(id)}, function (__exports, __require) {\n'use strict';\n${out}\n${tail}\n});\n`;
}

/* Collect the import graph from the entry files (depth-first, deduped). */
export function collectModules(entries, files) {
  const order = [];
  const seen = new Set();
  const visit = (id, chain) => {
    if (seen.has(id)) return;
    if (chain.includes(id)) throw new Error('import cycle: ' + [...chain, id].join(' -> '));
    const src = files(id);
    const deps = [];
    const dir = path.posix.dirname(id);
    for (const m of src.matchAll(/(^|\n)import\s*\{[^}]*\}\s*from\s*(['"])([^'"]+)\2/g)) deps.push(path.posix.normalize(path.posix.join(dir, m[3])));
    for (const d of deps) visit(d, [...chain, id]);
    seen.add(id);
    order.push(id);
  };
  for (const e of entries) visit(e, []);
  return order;
}

export function buildBundle({ files, entries = ['embed/shell.js', 'dock.js'] }) {
  const ids = collectModules(entries, files);
  let body = '';
  for (const id of ids) body += transformModule(files(id), id);
  return HEADER
    + '(function () {\n'
    + 'var __mods = Object.create(null), __cache = Object.create(null);\n'
    + 'function __define(id, fn) { __mods[id] = fn; }\n'
    + 'function __require(id) {\n'
    + '  if (__cache[id]) return __cache[id].exports;\n'
    + '  if (!__mods[id]) throw new Error("[ArenaKit] missing module " + id);\n'
    + '  var m = __cache[id] = { exports: {} };\n'
    + '  __mods[id](m.exports, __require);\n'
    + '  return m.exports;\n'
    + '}\n'
    + body
    + '// Test hook: hand the registry to the caller instead of mounting.\n'
    + 'var __hook = globalThis.__ARENAKIT_BUNDLE_HOOK__;\n'
    + 'if (typeof __hook === "function") { __hook(__require); return; }\n'
    + '// Mount the shell first (publishes __ARENAKIT_EMBED__), then boot the dock in it.\n'
    + 'var __shell = __require("embed/shell.js");\n'
    + 'if (__shell.mount(globalThis)) { __require("dock.js"); }\n'
    + '})();\n';
}

/* One lib module (plus its imports) as a classic script that publishes the
 * module's exports on a global — for injected/ page scripts that run on
 * origins where the dock (and IPC) is unavailable, e.g. accounts.google.com
 * during a 2-step login. */
export function buildPageLib({ files, entry, globalName }) {
  const ids = collectModules([entry], files);
  let body = '';
  for (const id of ids) body += transformModule(files(id), id);
  return HEADER
    + `/* ${entry} → window.${globalName} (classic script, no module loader needed). */\n`
    + '(function () {\n'
    + 'var __mods = Object.create(null), __cache = Object.create(null);\n'
    + 'function __define(id, fn) { __mods[id] = fn; }\n'
    + 'function __require(id) {\n'
    + '  if (__cache[id]) return __cache[id].exports;\n'
    + '  if (!__mods[id]) throw new Error("[ArenaKit] missing module " + id);\n'
    + '  var m = __cache[id] = { exports: {} };\n'
    + '  __mods[id](m.exports, __require);\n'
    + '  return m.exports;\n'
    + '}\n'
    + body
    + `globalThis.${globalName} = __require(${JSON.stringify(entry)});\n`
    + '})();\n';
}

export function generate() {
  const css = read(path.join(SRC, 'dock.css'));
  const html = read(path.join(SRC, 'dock.html'));
  const assets = buildAssets({ css, html });
  const files = (id) => (id === 'embed/assets.gen.js' ? assets : read(path.join(SRC, id)));
  const bundle = buildBundle({ files });
  const totp = buildPageLib({ files, entry: 'lib/totp.js', globalName: '__AK_TOTP__' });
  // Must at least parse as classic scripts.
  new vm.Script(bundle, { filename: 'dock-embedded.gen.js' });
  new vm.Script(totp, { filename: 'totp.gen.js' });
  return { assets, bundle, totp };
}

function main() {
  const check = process.argv.includes('--check');
  const { assets, bundle, totp } = generate();
  const targets = [[OUT_ASSETS, assets], [OUT_BUNDLE, bundle], [OUT_TOTP, totp]];
  if (check) {
    const stale = targets.filter(([p, content]) => !fs.existsSync(p) || read(p) !== content).map(([p]) => path.relative(ROOT, p));
    if (stale.length) {
      console.error('Embedded dock bundle is stale: ' + stale.join(', ') + '\nRun: node scripts/bundle-dock.mjs');
      process.exit(1);
    }
    console.log('bundle-dock: up to date');
    return;
  }
  fs.mkdirSync(path.dirname(OUT_BUNDLE), { recursive: true });
  for (const [p, content] of targets) fs.writeFileSync(p, content);
  console.log(`bundle-dock: wrote ${path.relative(ROOT, OUT_ASSETS)}, ${path.relative(ROOT, OUT_BUNDLE)} (${bundle.length} bytes) and ${path.relative(ROOT, OUT_TOTP)} (${totp.length} bytes)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
